// WeightHelpers.cpp
// Self-contained ROOT macro for deriving and applying data/MC weights from histograms
// Author: GitHub Copilot, 2025-07-31
// Usage (ROOT): .x WeightHelpers.cpp+("data.root","mc.root","histname","weights.txt",normalizeMode,underflowMode)
// normalizeMode: 0=raw, 1=normalize to integral, 2=normalize to density (integral/bin width)
// underflowMode: 0=weight 0 for under/overflow, 1=weight 1

#include <iostream>
#include <fstream>
#include <vector>
#include <string>
#include <cmath>
#include <algorithm>
#include <stdexcept>
#include <iomanip>
#include "TFile.h"
#include "TH1.h"
#include "TTree.h"

struct WeightBin {
    double low, high, weight;
};

// Helper: Read TH1 from file
TH1* getHistFromFile(const std::string& fname, const std::string& hname) {
    TFile* f = TFile::Open(fname.c_str());
    if (!f || f->IsZombie()) throw std::runtime_error("Cannot open file: " + fname);
    TH1* h = dynamic_cast<TH1*>(f->Get(hname.c_str()));
    if (!h) throw std::runtime_error("Histogram not found: " + hname + " in " + fname);
    h->SetDirectory(0); // Detach from file
    f->Close();
    delete f;
    return h;
}

